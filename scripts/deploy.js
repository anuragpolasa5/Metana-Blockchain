// scripts/deploy.js
// Deploys LearnToken + TokenSale, wires up MINTER_ROLE, and writes
// addresses/ABIs into frontend/config.js for the DApp.

const { ethers } = require("hardhat");
const fs = require("fs");
const path = require("path");

// ─── Token Parameters ─────────────────────────────────────────────────────────
const MAX_SUPPLY_UNITS = 1_000_000n;          // 1 million LRN (whole tokens)
const BUY_PRICE  = ethers.parseEther("0.001"); // 0.001 ETH per token
const SELL_PRICE = ethers.parseEther("0.0005");// 0.0005 ETH per token

// ─── Network configs ─────────────────────────────────────────────────────────
const NETWORKS = {
  31337: {
    chainId: 31337,
    chainIdHex: "0x7a69",
    name: "Localhost",
    rpcUrl: "http://127.0.0.1:8545",
    blockExplorer: "",
    nativeCurrency: { name: "Ether", symbol: "ETH", decimals: 18 },
  },
  11155111: {
    chainId: 11155111,
    chainIdHex: "0xaa36a7",
    name: "Sepolia",
    rpcUrl: "https://rpc.sepolia.org",
    blockExplorer: "https://sepolia.etherscan.io",
    nativeCurrency: { name: "Ether", symbol: "ETH", decimals: 18 },
  },
};

async function main() {
  const network = await ethers.provider.getNetwork();
  const chainId = Number(network.chainId);
  const netCfg = NETWORKS[chainId] || NETWORKS[11155111];
  const [deployer] = await ethers.getSigners();
  console.log("Deploying with account:", deployer.address);
  console.log(
    "Account balance:",
    ethers.formatEther(await ethers.provider.getBalance(deployer.address)),
    "ETH"
  );

  // ── 1. Deploy LearnToken ──────────────────────────────────────────────────
  console.log("\n📦  Deploying LearnToken …");
  const LearnToken = await ethers.getContractFactory("LearnToken");
  const learnToken = await LearnToken.deploy("LearnToken", "LRN", 18, MAX_SUPPLY_UNITS, deployer.address, { gasLimit: 6_000_000 });
  await learnToken.waitForDeployment();
  const tokenAddress = await learnToken.getAddress();
  console.log("✅  LearnToken deployed to:", tokenAddress);

  // ── 2. Deploy TokenSale ───────────────────────────────────────────────────
  console.log("\n📦  Deploying TokenSale …");
  const TokenSale = await ethers.getContractFactory("TokenSale");
  const tokenSale = await TokenSale.deploy(tokenAddress, SELL_PRICE, BUY_PRICE, deployer.address, { gasLimit: 6_000_000 });
  await tokenSale.waitForDeployment();
  const saleAddress = await tokenSale.getAddress();
  console.log("✅  TokenSale deployed to:", saleAddress);

  // ── 3. Grant MINTER_ROLE to TokenSale (FE-6) ─────────────────────────────
  console.log("\n🔑  Granting MINTER_ROLE to TokenSale …");
  const MINTER_ROLE = await learnToken.MINTER_ROLE();
  const grantTx = await learnToken.grantRole(MINTER_ROLE, saleAddress, { gasLimit: 200_000 });
  await grantTx.wait();
  console.log("✅  MINTER_ROLE granted to TokenSale");

  // ── 4. Write frontend/config.js ───────────────────────────────────────────
  const frontendDir = path.join(__dirname, "..", "frontend");
  if (!fs.existsSync(frontendDir)) {
    fs.mkdirSync(frontendDir, { recursive: true });
  }

  // Read compiled ABIs
  const tokenArtifact = require(
    path.join(__dirname, "..", "artifacts", "contracts", "LearnToken.sol", "LearnToken.json")
  );
  const saleArtifact = require(
    path.join(__dirname, "..", "artifacts", "contracts", "TokenSale.sol", "TokenSale.json")
  );

  // Write ABI JSON files
  const abiDir = path.join(frontendDir, "abi");
  if (!fs.existsSync(abiDir)) {
    fs.mkdirSync(abiDir, { recursive: true });
  }
  fs.writeFileSync(
    path.join(abiDir, "LearnToken.json"),
    JSON.stringify(tokenArtifact.abi, null, 2)
  );
  fs.writeFileSync(
    path.join(abiDir, "TokenSale.json"),
    JSON.stringify(saleArtifact.abi, null, 2)
  );

  // Write config.js
  const configContent = `// AUTO-GENERATED by scripts/deploy.js – do not edit manually
// Last deployed: ${new Date().toISOString()}

const NETWORK_CONFIG = {
  chainId: ${netCfg.chainId},
  chainIdHex: "${netCfg.chainIdHex}",
  name: "${netCfg.name}",
  rpcUrl: "${netCfg.rpcUrl}",
  blockExplorer: "${netCfg.blockExplorer}",
  nativeCurrency: { name: "Ether", symbol: "ETH", decimals: 18 },
};

const CONTRACT_ADDRESSES = {
  learnToken: "${tokenAddress}",
  tokenSale: "${saleAddress}",
};

const TOKEN_CONFIG = {
  buyPrice: "${BUY_PRICE.toString()}",   // wei
  sellPrice: "${SELL_PRICE.toString()}",  // wei
  decimals: 18,
  symbol: "LRN",
  name: "LearnToken",
};
`;
  fs.writeFileSync(path.join(frontendDir, "config.js"), configContent);

  console.log("\n📄  Frontend config written to frontend/config.js");
  console.log("📄  ABIs written to frontend/abi/");

  // ── 5. Summary ────────────────────────────────────────────────────────────
  console.log("\n─────────────────────────────────────────────");
  console.log("Deployment summary");
  console.log("─────────────────────────────────────────────");
  console.log("LearnToken :", tokenAddress);
  console.log("TokenSale  :", saleAddress);
  console.log("Network    :", netCfg.name);
  console.log("─────────────────────────────────────────────\n");
  console.log("Next steps:");
  console.log("  1. Verify on Etherscan:");
  console.log(`     npx hardhat verify --network sepolia ${tokenAddress} ${MAX_SUPPLY_UNITS} ${deployer.address}`);
  console.log(`     npx hardhat verify --network sepolia ${saleAddress} ${tokenAddress} ${SELL_PRICE} ${BUY_PRICE}`);
  console.log("  2. Open frontend/index.html in a browser with MetaMask installed.");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
